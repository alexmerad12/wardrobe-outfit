// Android app icons, generated from the app's own icon (public/icon.svg:
// a black tile with the white script L). Run it again whenever that
// file changes:
//
//   node scripts/android-icons.mjs [--store] [--preview some/file.png]
//
// What it writes under android/app/src/main/res:
//  - drawable/ic_launcher_foreground.xml  the L alone, as a vector. It is
//    the foreground of the adaptive icon (Android 8+), its themed-icon
//    layer (Android 13+) and the icon of the system launch screen, so it
//    stays sharp at every size. Its scale is computed here so the whole
//    letter sits inside Android's 66dp safe zone: launchers mask the icon
//    with a circle, a squircle or a rounded square, and anything outside
//    that zone can be cut.
//  - mipmap-*/ic_launcher.png and ic_launcher_round.png  plain images for
//    Android 7 (the app's oldest version), which has no adaptive icons.
// It also removes the Capacitor template's own icon files, which would
// otherwise win over ours (drawable-v24 beats drawable).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const res = path.join(root, "android", "app", "src", "main", "res");
const iconSvg = fs.readFileSync(path.join(root, "public", "icon.svg"), "utf8");

const pathMatch = iconSvg.match(/<path fill="#ffffff" d="([^"]+)"/);
if (!pathMatch) throw new Error("public/icon.svg: the white L path was not found");
const letter = pathMatch[1].trim();
// Android's vector format reads the same path commands as SVG. Stop if
// the path ever uses one this script has not been checked with.
const commands = [...new Set(letter.replace(/[0-9.\s-]/g, ""))].join("");
if (!/^[MLQCZ]+$/.test(commands)) throw new Error(`unexpected path commands: ${commands}`);

const VIEW = 400; // icon.svg's canvas; the letter is drawn around its centre
const CENTRE = VIEW / 2;

const letterSvg = (scale, size, extra = "") =>
  Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW} ${VIEW}" width="${size}" height="${size}">${extra}` +
      `<g transform="translate(${CENTRE} ${CENTRE}) scale(${scale}) translate(${-CENTRE} ${-CENTRE})">` +
      `<path fill="#ffffff" d="${letter}"/></g></svg>`,
  );

// How far the letter reaches from the centre, measured on a large render.
const MEASURE = 2000;
const { data, info } = await sharp(letterSvg(1, MEASURE)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
let reach = 0;
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] < 8) continue;
    const ux = ((x + 0.5) / info.width) * VIEW;
    const uy = ((y + 0.5) / info.height) * VIEW;
    reach = Math.max(reach, Math.hypot(ux - CENTRE, uy - CENTRE));
    minX = Math.min(minX, ux); maxX = Math.max(maxX, ux);
    minY = Math.min(minY, uy); maxY = Math.max(maxY, uy);
  }
}
if (!reach) throw new Error("the letter rendered empty");

// The adaptive icon's canvas is 108dp: launchers show its central 72dp and
// promise only the central 66dp circle. Same proportions on the system
// launch screen (288dp canvas, 192dp circle). 4% of air inside the zone.
const SAFE_RADIUS = (33 / 108) * VIEW;
const VISIBLE_RADIUS = (36 / 108) * VIEW;
const foregroundScale = Math.floor(((SAFE_RADIUS * 0.96) / reach) * 100) / 100;
// The round image for Android 7 is the whole disc: the letter can be
// larger there, as on the tile.
const roundScale = Math.min(1.2, Math.floor(((CENTRE * 0.8) / reach) * 100) / 100);

console.log(
  `letter: x ${minX.toFixed(1)}-${maxX.toFixed(1)}, y ${minY.toFixed(1)}-${maxY.toFixed(1)}, reach ${reach.toFixed(1)} of ${VIEW}`,
);
console.log(
  `adaptive foreground scale ${foregroundScale} (reach ${(reach * foregroundScale).toFixed(1)}, safe zone ${SAFE_RADIUS.toFixed(1)}, visible ${VISIBLE_RADIUS.toFixed(1)})`,
);
console.log(`round image scale ${roundScale}`);

// 1. The vector.
const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs from public/icon.svg. Do not
     edit by hand: change the icon, then run the script again. The white
     script L alone, scaled to stay inside the 66dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${VIEW}"
    android:viewportHeight="${VIEW}">
    <group
        android:pivotX="${CENTRE}"
        android:pivotY="${CENTRE}"
        android:scaleX="${foregroundScale}"
        android:scaleY="${foregroundScale}">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="${letter}" />
    </group>
</vector>
`;
fs.mkdirSync(path.join(res, "drawable"), { recursive: true });
fs.writeFileSync(path.join(res, "drawable", "ic_launcher_foreground.xml"), vector);
console.log("wrote drawable/ic_launcher_foreground.xml");

// 2. The plain images for Android 7.
const densities = [["mdpi", 1], ["hdpi", 1.5], ["xhdpi", 2], ["xxhdpi", 3], ["xxxhdpi", 4]];
const disc = `<circle cx="${CENTRE}" cy="${CENTRE}" r="${CENTRE}" fill="#000000"/>`;
for (const [name, scale] of densities) {
  const dir = path.join(res, `mipmap-${name}`);
  fs.mkdirSync(dir, { recursive: true });
  const size = Math.round(48 * scale);
  await sharp(Buffer.from(iconSvg), { density: 400 }).resize(size, size).png().toFile(path.join(dir, "ic_launcher.png"));
  await sharp(letterSvg(roundScale, size * 4, disc)).resize(size, size).png().toFile(path.join(dir, "ic_launcher_round.png"));
  // The first version of this script wrote the foreground as an image.
  fs.rmSync(path.join(dir, "ic_launcher_foreground.png"), { force: true });
  console.log(`mipmap-${name}: ${size}px`);
}

// 3. The template's own icon art.
for (const leftover of [["drawable-v24", "ic_launcher_foreground.xml"], ["drawable", "ic_launcher_background.xml"]]) {
  const file = path.join(res, ...leftover);
  if (fs.existsSync(file)) {
    fs.rmSync(file);
    console.log(`removed the template's ${leftover.join("/")}`);
  }
  const dir = path.join(res, leftover[0]);
  if (fs.existsSync(dir) && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
}

// 3b. Optional (--store): the Google Play listing icon. 512 x 512, a full
// square with no transparency: Google rounds the corners itself, so the
// tile's own rounded corners are squared off here. The letter keeps the
// size it has on the web icon.
if (process.argv.includes("--store")) {
  const storeDir = path.join(root, "store", "android");
  fs.mkdirSync(storeDir, { recursive: true });
  const square = iconSvg.replace(/\srx="[^"]*"/, "").replace(/\sry="[^"]*"/, "");
  if (square === iconSvg) throw new Error("public/icon.svg: the tile's rounded corners were not found");
  await sharp(Buffer.from(square), { density: 400 })
    .resize(512, 512)
    .flatten({ background: "#000000" })
    .ensureAlpha() // Google asks for a 32-bit PNG: the channel is there, fully opaque
    .png()
    .toFile(path.join(storeDir, "icon-512.png"));
  console.log("wrote store/android/icon-512.png");
}

// 4. Optional preview: what a launcher shows (circle, then squircle), the
// Android 7 pair, and the launch screen. The red ring is the safe zone.
const previewAt = process.argv.indexOf("--preview");
if (previewAt !== -1 && process.argv[previewAt + 1]) {
  const out = path.resolve(process.argv[previewAt + 1]);
  const TILE = 288;
  const ring = `<circle cx="${CENTRE}" cy="${CENTRE}" r="${SAFE_RADIUS}" fill="none" stroke="#ff3b30" stroke-width="1.5"/>`;
  const masked = (clip) =>
    Buffer.from(
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${CENTRE - VISIBLE_RADIUS} ${CENTRE - VISIBLE_RADIUS} ${VISIBLE_RADIUS * 2} ${VISIBLE_RADIUS * 2}" width="${TILE}" height="${TILE}">` +
        `<defs><clipPath id="m">${clip}</clipPath></defs><g clip-path="url(#m)"><rect width="${VIEW}" height="${VIEW}" fill="#000000"/>` +
        `<g transform="translate(${CENTRE} ${CENTRE}) scale(${foregroundScale}) translate(${-CENTRE} ${-CENTRE})"><path fill="#ffffff" d="${letter}"/></g></g>${ring}</svg>`,
    );
  const circle = await sharp(masked(`<circle cx="${CENTRE}" cy="${CENTRE}" r="${VISIBLE_RADIUS}"/>`)).png().toBuffer();
  const side = VISIBLE_RADIUS * 2;
  const squircle = await sharp(
    masked(`<rect x="${CENTRE - VISIBLE_RADIUS}" y="${CENTRE - VISIBLE_RADIUS}" width="${side}" height="${side}" rx="${side * 0.28}"/>`),
  ).png().toBuffer();
  const legacy = await sharp(path.join(res, "mipmap-xxxhdpi", "ic_launcher.png")).resize(TILE, TILE).toBuffer();
  const legacyRound = await sharp(path.join(res, "mipmap-xxxhdpi", "ic_launcher_round.png")).resize(TILE, TILE).toBuffer();
  // Launch screen: a 288dp icon canvas centred on a black phone screen
  // (drawn at 0.7 px per dp), the 192dp circle the system keeps.
  const PHONE_W = Math.round(411 * 0.7), PHONE_H = Math.round(891 * 0.7), ICON = Math.round(288 * 0.7);
  const splashIcon = await sharp(letterSvg(foregroundScale, ICON)).png().toBuffer();
  const phone = await sharp({ create: { width: PHONE_W, height: PHONE_H, channels: 4, background: "#000000" } })
    .composite([{ input: splashIcon, left: Math.round((PHONE_W - ICON) / 2), top: Math.round((PHONE_H - ICON) / 2) }])
    .png().toBuffer();
  const GAP = 24;
  const width = GAP + (TILE + GAP) * 2 + PHONE_W + GAP;
  const height = GAP + Math.max(TILE * 2 + GAP, PHONE_H) + GAP;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  await sharp({ create: { width, height, channels: 4, background: "#8a8a8a" } })
    .composite([
      { input: circle, left: GAP, top: GAP },
      { input: squircle, left: GAP + TILE + GAP, top: GAP },
      { input: legacy, left: GAP, top: GAP + TILE + GAP },
      { input: legacyRound, left: GAP + TILE + GAP, top: GAP + TILE + GAP },
      { input: phone, left: GAP + (TILE + GAP) * 2, top: GAP },
    ])
    .png().toFile(out);
  console.log(`preview: ${out}`);
}
